// Renders the trap catalogue section of content/ROADMAP.md from the verified trap files.

import {
  divergencePly,
  formatMoves,
  measureLine,
  parseMovetext,
  type ParsedMove,
} from '../../shared/movetext.ts';
import type { BacklogEntry, LineResult, TrapFile, TrapLine } from '../../shared/trap-types.ts';

export function formatResult(result: LineResult | undefined): string {
  if (!result) return 'not evaluated';
  if (result.end === 'checkmate') return 'checkmate';
  if (result.end === 'checkmated') return 'the player is checkmated';
  if (result.mate !== undefined) {
    return result.mate > 0 ? `forced mate in ${result.mate}` : `mated in ${-result.mate}`;
  }
  if (result.cp !== undefined) {
    const pawns = result.cp / 100;
    return `${pawns > 0 ? '+' : ''}${pawns.toFixed(1)}`;
  }
  return result.problem ?? 'not evaluated';
}

export function trapStatus(trap: TrapFile): 'verified' | 'unverified' | 'failed' {
  if (trap.verified) return 'verified';
  return trap.draft ? 'unverified' : 'failed';
}

function sourceLinks(sources: { label: string; url: string }[]): string {
  return sources.map((source) => `[${source.label}](${source.url})`).join('; ');
}

function deviation(main: ParsedMove[], line: TrapLine): string {
  const moves = parseMovetext(line.moves);
  const from = divergencePly(main, moves);
  return `${formatMoves(moves, from)} (${line.tag}, ${formatResult(line.result)})`;
}

function renderTrap(trap: TrapFile, number: number): string {
  const mainLine = trap.lines.find((line) => line.main) ?? trap.lines[0];
  const main = mainLine ? parseMovetext(mainLine.moves) : [];
  const shape = measureLine(main, trap.side);
  const startPly = shape.mistakePly ?? main.length;
  // One deviation where the opponent avoids the trap and one where they bail out, when both exist.
  const wanted = trap.kind === 'trap' ? ['sound', 'decline'] : ['punish', 'mistake'];
  const deviations = wanted
    .map((tag) => trap.lines.find((line) => line.tag === tag && !line.main))
    .filter((line): line is TrapLine => line !== undefined);
  for (const line of trap.lines) {
    if (deviations.length >= 2) break;
    if (!line.main && !deviations.includes(line)) deviations.push(line);
  }

  const status = trapStatus(trap);
  const problems = trap.verification?.problems ?? [];
  const facts = [
    `**Side:** ${trap.side === 'white' ? 'White' : 'Black'}`,
    `**Kind:** ${trap.kind}`,
    `**Repertoire:** ${trap.repertoire}`,
    `**Reliability:** ${trap.verification?.reliability ?? 'unknown'}`,
    `**Status:** ${status}`,
  ];
  const out = [
    `#### ${number}. ${trap.title.en} · ${trap.title.ru} (\`${trap.id}\`)`,
    '',
    `- ${facts.join(' · ')}`,
    `- **Start:** ${startPly > 0 ? formatMoves(main.filter((move) => move.ply < startPly)) : 'the initial position'}`,
    `- **Idea:** ${trap.idea.en}`,
    `- **Correct line:** ${formatMoves(main, startPly) || formatMoves(main)} (${formatResult(mainLine?.result)})`,
  ];
  if (deviations.length > 0) {
    out.push(`- **If the opponent deviates:** ${deviations.map((line) => deviation(main, line)).join('; ')}`);
  }
  if (trap.notes) out.push(`- **Note:** ${trap.notes}`);
  if (problems.length > 0) out.push(`- **Problems:** ${problems.join(' | ')}`);
  out.push(`- **Source:** ${sourceLinks(trap.sources)}`);
  return out.join('\n');
}

export function renderCatalog(traps: TrapFile[], backlog: BacklogEntry[]): string {
  const counts = { verified: 0, unverified: 0, failed: 0 };
  for (const trap of traps) counts[trapStatus(trap)]++;
  const lineCount = traps.reduce((sum, trap) => sum + trap.lines.length, 0);
  const lineOk = traps.reduce(
    (sum, trap) => sum + trap.lines.filter((line) => line.result?.ok).length,
    0,
  );

  const out: string[] = [
    '_This section is generated by `npm run verify` from `content/traps/*.json`. Do not edit it by hand._',
    '',
    `**${traps.length} traps with written lines:** ${counts.verified} verified, ${counts.failed} failed, ` +
      `${counts.unverified} unverified drafts. **${lineCount} lines:** ${lineOk} pass. ` +
      `**${backlog.length} more names** are in the backlog without lines (unverified).`,
    '',
    'Evaluations are from the player\'s point of view, in pawns. "decline": the opponent walks in ' +
      'and bails out. "sound": the opponent avoids it.',
  ];

  out.push(
    '',
    '### Stage overview',
    '',
    'The stage of a trap is the `stage` field of its file and its place inside the stage is the ' +
      '`order` field. Moving a trap is a data change. Practice opens in the order of this table.',
    '',
    '| Trap | Stage | Order | Why |',
    '| --- | --- | --- | --- |',
  );
  for (const trap of traps) {
    out.push(`| ${trap.title.en} (\`${trap.id}\`) | ${trap.stage} | ${trap.order} | ${trap.stageReason} |`);
  }

  const stages = [...new Set(traps.map((trap) => trap.stage))].sort((a, b) => a - b);
  let number = 0;
  for (const stage of stages) {
    out.push('', `### Stage ${stage}`, '');
    const inStage = traps.filter((trap) => trap.stage === stage);
    out.push(inStage.map((trap) => renderTrap(trap, ++number)).join('\n\n'));
  }

  if (backlog.length > 0) {
    out.push(
      '',
      '### Backlog: names without lines (all unverified)',
      '',
      'Each name was confirmed to exist in the linked source. No line has been written or checked.',
      '',
      '| Name | Side | Repertoire | Note | Source |',
      '| --- | --- | --- | --- | --- |',
    );
    for (const entry of backlog) {
      out.push(
        `| ${entry.name} | ${entry.side} | ${entry.repertoire} | ${entry.note} | ${sourceLinks(entry.sources)} |`,
      );
    }
  }
  return out.join('\n');
}

export const CATALOG_START = '<!-- catalog:start -->';
export const CATALOG_END = '<!-- catalog:end -->';

/** Replaces the text between the catalogue markers. Returns the input unchanged if they are missing. */
export function injectCatalog(document: string, catalog: string): string {
  const start = document.indexOf(CATALOG_START);
  const end = document.indexOf(CATALOG_END);
  if (start < 0 || end < start) return document;
  return `${document.slice(0, start + CATALOG_START.length)}\n\n${catalog}\n\n${document.slice(end)}`;
}
